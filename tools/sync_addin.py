"""Copy the shared IR helpers (src/fuse2sc/ir) into the Fusion add-in (fusion_addin/Fuse2SC/fuse2sc_ir).

The add-in runs on Fusion's embedded Python and can't import the fuse2sc package, so it carries a
copy; tests/unit/test_addin_sync.py fails when the copy differs.

    python tools/sync_addin.py           copy
    python tools/sync_addin.py --check   report whether they differ (exit 1 if so)
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "fuse2sc" / "ir"
DST = ROOT / "fusion_addin" / "Fuse2SC" / "fuse2sc_ir"
HEADER = "# GENERATED by tools/sync_addin.py from src/fuse2sc/ir: edit there, not here.\n"


def sources() -> list[Path]:
	return sorted(SRC.glob("*.py"))


def expected(src: Path) -> str:
	return HEADER + src.read_text(encoding="utf-8")


def differs() -> list[str]:
	have = sorted(p.name for p in DST.glob("*.py")) if DST.is_dir() else []
	want = [p.name for p in sources()]
	problems = [f"file list: {have} vs {want}"] if have != want else []
	for src in sources():
		dst = DST / src.name
		if not dst.is_file():
			problems.append(f"missing {src.name}")
		elif dst.read_text(encoding="utf-8") != expected(src):
			problems.append(f"differs: {src.name}")
	return problems


def sync() -> None:
	shutil.rmtree(DST, ignore_errors=True)
	DST.mkdir(parents=True)
	for src in sources():
		(DST / src.name).write_text(expected(src), encoding="utf-8", newline="\n")


if __name__ == "__main__":
	if "--check" in sys.argv:
		problems = differs()
		print("\n".join(problems) or "in sync")
		sys.exit(1 if problems else 0)
	sync()
	print(f"copied {len(sources())} files to {DST}")
